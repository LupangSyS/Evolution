const DECK_SIZE = Object.values(TRAITS).reduce((s, t) => s + t.food.length, 0);

function buildDeck() {
  const deck = [];
  let id = 1;
  for (const [trait, info] of Object.entries(TRAITS)) {
    for (const food of info.food) deck.push({ id: id++, trait, food });
  }
  return deck;
}

const cardStr = (c) => `「${TRAITS[c.trait].name}」`;

